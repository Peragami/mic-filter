#!/usr/bin/env python3
"""Train the tiny bandwidth-extension (BWE) gain predictor.

Approach (RNNoise-style hybrid): the HF waveform itself is generated by DSP
(rectified source band), and a small MLP only predicts the *gains* of three
HF bands (7-9.5k, 9.5-12k, 12-16k) from low-band features of the degraded
input. Training data is synthetic: full-band harmonic "voice" (formant
envelopes, f0 contours, aspiration noise, fricative bursts) low-passed to
simulate a cheap mic. The runtime (Source/dsp/BweStage.h) replicates this
exact feature extraction.

Outputs: Source/dsp/BweWeights.h
"""
import numpy as np
from scipy.signal import lfilter

SR = 48000
FRAME = 480

def rbj(kind, f, q=0.7071):
    w = 2 * np.pi * f / SR
    cw, sw = np.cos(w), np.sin(w)
    al = sw / (2 * q)
    if kind == 'bp':  # constant 0 dB peak gain
        return np.array([al, 0, -al]) / (1 + al), np.array([1, -2 * cw / (1 + al), (1 - al) / (1 + al)])
    if kind == 'hp':
        return np.array([(1 + cw) / 2, -(1 + cw), (1 + cw) / 2]) / (1 + al), np.array([1, -2 * cw / (1 + al), (1 - al) / (1 + al)])
    if kind == 'lp':
        return np.array([(1 - cw) / 2, 1 - cw, (1 - cw) / 2]) / (1 + al), np.array([1, -2 * cw / (1 + al), (1 - al) / (1 + al)])
    raise ValueError(kind)

SRC_BANDS = [(300, 800), (800, 1500), (1500, 2500), (2500, 3500), (3500, 5000), (5000, 6500)]
TGT_BANDS = [(7000, 9500), (9500, 12000), (12000, 16000)]
_fcache = {}
def band_filter(lo, hi):
    key = (lo, hi)
    if key not in _fcache:
        fc = np.sqrt(lo * hi)
        q = fc / (hi - lo)
        _fcache[key] = rbj('bp', fc, q)
    return _fcache[key]

def band_energy(x, lo, hi):
    b, a = band_filter(lo, hi)
    y = lfilter(b, a, x)
    return float(np.mean(y * y))

def excitation(x):
    """DSP excitation exactly as the C++ stage builds it."""
    b, a = rbj('hp', 3500.0)
    s = lfilter(b, a, x)
    b, a = rbj('lp', 7000.0)
    s = lfilter(b, a, s)
    return np.abs(s)

def mic_rolloff(seg, rng):
    """Cheap-mic simulation: flat to ~5k, steep fall to nothing by ~8k."""
    n = len(seg)
    spec = np.fft.rfft(seg)
    freqs = np.fft.rfftfreq(n, 1 / SR)
    knee = rng.uniform(4800, 5800)
    top = rng.uniform(7200, 8400)
    g = np.ones_like(freqs)
    m = (freqs > knee) & (freqs < top)
    g[m] = 0.5 * (1 + np.cos(np.pi * (freqs[m] - knee) / (top - knee)))
    g[freqs >= top] = 0.0
    return np.fft.irfft(spec * g, n).astype(np.float32)

def gen_segment(rng):
    dur = rng.uniform(0.8, 1.6)
    n = int(dur * SR)
    t = np.arange(n) / SR
    # --- voiced harmonic source
    f0 = rng.uniform(75, 280)
    steps = rng.standard_normal(int(np.ceil(n / 240)))
    f0c = f0 * np.cumprod(1 + 0.0006 * steps)[np.arange(n) // 240]
    vib = 1 + 0.006 * np.sin(2 * np.pi * rng.uniform(4, 6) * t)
    phase = 2 * np.pi * np.cumsum(f0c * vib) / SR
    # formant envelope (per segment, slight drift via two mixes)
    def envelope(freqs):
        env = np.full_like(freqs, 0.02)
        for _ in range(rng.integers(3, 5)):
            fc = rng.uniform(250, 3800)
            bw = rng.uniform(80, 500)
            amp = rng.uniform(0.4, 1.0)
            env += amp * np.exp(-0.5 * ((freqs - fc) / bw) ** 2)
        tilt = 10 ** (-rng.uniform(0.5, 2.2) * np.log10(np.maximum(freqs, 1) / 500) / 10)
        return env * tilt
    nh = int(16000 / f0) + 1
    harm_f = f0 * np.arange(1, nh + 1)
    env = envelope(harm_f)
    sig = np.zeros(n)
    chunk = 8192
    for s in range(0, n, chunk):
        e = min(n, s + chunk)
        sig[s:e] = np.sum(env[None, :] * np.sin(phase[s:e, None] * np.arange(1, nh + 1)[None, :]), axis=1)
    # aspiration noise shaped loosely like the harmonic envelope (lowpassed white + HF shelf)
    noise = rng.standard_normal(n).astype(np.float32)
    b, a = rbj('lp', 9000.0)
    asp = lfilter(b, a, noise)
    sig += rng.uniform(0.0, 0.25) * asp / max(1e-9, np.max(np.abs(asp))) * np.max(np.abs(sig))
    # syllable-ish amplitude contour with pauses
    contour = np.zeros(n)
    pos = 0
    while pos < n:
        ln = int(rng.uniform(0.12, 0.45) * SR)
        contour[pos:pos + ln] = rng.uniform(0.4, 1.0)
        pos += ln + int(rng.uniform(0.03, 0.25) * SR)
    k = int(0.01 * SR)
    contour = np.convolve(contour, np.hanning(k) / np.hanning(k).sum(), 'same')
    sig *= contour
    # fricative bursts: bandpassed noise replacing some voiced parts
    for _ in range(rng.integers(0, 3)):
        s = rng.integers(0, max(1, n - int(0.15 * SR)))
        ln = int(rng.uniform(0.05, 0.15) * SR)
        fr = rng.standard_normal(ln).astype(np.float32)
        b, a = rbj('bp', rng.uniform(4500, 7000), 0.6)
        fr = lfilter(b, a, fr)
        fr *= rng.uniform(0.2, 0.6) / max(1e-9, np.max(np.abs(fr))) * np.max(np.abs(sig))
        sig[s:s + ln] = fr * np.hanning(ln) + sig[s:s + ln] * 0.2
    peak = np.max(np.abs(sig)) + 1e-9
    return (sig / peak * rng.uniform(0.3, 0.9)).astype(np.float32)

def segment_bands(degr, full):
    """Continuously filter the whole segment (the C++ runtime filters
    continuously too, so energies must come from continuous filtering,
    not per-frame restarts). Returns per-band squared signals."""
    src_sq = []
    for lo, hi in SRC_BANDS:
        b, a = band_filter(lo, hi)
        y = lfilter(b, a, degr)
        src_sq.append(y * y)
    exc = excitation(degr)
    exc_sq = []
    for lo, hi in TGT_BANDS:
        b, a = band_filter(lo, hi)
        y = lfilter(b, a, exc)
        exc_sq.append(y * y)
    tgt_sq = []
    for lo, hi in TGT_BANDS:
        b, a = band_filter(lo, hi)
        y = lfilter(b, a, full)
        tgt_sq.append(y * y)
    return src_sq, exc_sq, tgt_sq

def frame_features(degr, bands, idx0):
    """Returns (features[11], targets[3]) for the frame starting at idx0."""
    src_sq, exc_sq, tgt_sq = bands
    fr = degr[idx0:idx0 + FRAME]
    feats = []
    for sq in src_sq:
        feats.append(10 * np.log10(np.mean(sq[idx0:idx0 + FRAME]) + 1e-10))
    exc_e = []
    for sq in exc_sq:
        exc_e.append(10 * np.log10(np.mean(sq[idx0:idx0 + FRAME]) + 1e-10))
    feats += exc_e
    # voicing: normalised autocorrelation peak over lags 40..640, needs history
    hist = degr[max(0, idx0 - 640):idx0 + FRAME]
    if len(hist) < FRAME + 640:
        voicing = 0.0
    else:
        x = hist[-FRAME - 640:]
        best = 0.0
        base = np.dot(x[640:], x[640:]) + 1e-9
        for lag in range(40, 641, 4):
            v = np.dot(x[640 - lag:640 - lag + FRAME], x[640:]) / base
            best = max(best, v)
        voicing = float(np.clip(best, 0, 1))
    feats.append(voicing)
    feats.append(10 * np.log10(np.mean(fr * fr) + 1e-10))
    tgts = []
    for j in range(3):
        true_e = 10 * np.log10(np.mean(tgt_sq[j][idx0:idx0 + FRAME]) + 1e-10)
        tgts.append(float(np.clip(true_e - exc_e[j], -40, 20)))
    if feats[-1] < -55:  # silence -> HF fully off
        tgts = [-40.0, -40.0, -40.0]
    return np.array(feats, np.float32), np.array(tgts, np.float32)

def build_dataset(n_segments, seed):
    rng = np.random.default_rng(seed)
    X, Y = [], []
    for _ in range(n_segments):
        full = gen_segment(rng)
        degr = mic_rolloff(full, rng)
        bands = segment_bands(degr, full)
        nf = len(full) // FRAME - 1
        for fi in range(1, nf):
            f, t = frame_features(degr, bands, fi * FRAME)
            X.append(f)
            Y.append(t)
    return np.array(X), np.array(Y)

def main():
    print("building dataset...")
    Xtr, Ytr = build_dataset(500, 1)
    Xva, Yva = build_dataset(80, 2)
    print("train", Xtr.shape, "val", Xva.shape)
    mu, sd = Xtr.mean(0), Xtr.std(0) + 1e-6
    Xtr_n = (Xtr - mu) / sd
    Xva_n = (Xva - mu) / sd

    # --- tiny MLP 11 -> 48 -> 48 -> 3, manual Adam
    rng = np.random.default_rng(0)
    def init(fan_in, fan_out):
        return (rng.standard_normal((fan_in, fan_out)) * np.sqrt(2 / fan_in)).astype(np.float32)
    W1, b1 = init(11, 48), np.zeros(48, np.float32)
    W2, b2 = init(48, 48), np.zeros(48, np.float32)
    W3, b3 = init(48, 3), np.zeros(3, np.float32)
    b3[:] = -20.0  # start conservative (HF mostly off)
    params = [W1, b1, W2, b2, W3, b3]
    ms = [np.zeros_like(p) for p in params]
    vs = [np.zeros_like(p) for p in params]

    def forward(X, train=False):
        h1 = np.tanh(X @ W1 + b1)
        h2 = np.tanh(h1 @ W2 + b2)
        out = h2 @ W3 + b3
        return out, (X, h1, h2)

    epochs, bs, lr = 60, 512, 2e-3
    for ep in range(epochs):
        perm = rng.permutation(len(Xtr_n))
        for s in range(0, len(perm), bs):
            idx = perm[s:s + bs]
            xb, yb = Xtr_n[idx], Ytr[idx]
            out, (x0, h1, h2) = forward(xb)
            n = len(idx)
            dout = 2 * (out - yb) / n
            gW3 = h2.T @ dout; gb3 = dout.sum(0)
            dh2 = (dout @ W3.T) * (1 - h2 ** 2)
            gW2 = h1.T @ dh2; gb2 = dh2.sum(0)
            dh1 = (dh2 @ W2.T) * (1 - h1 ** 2)
            gW1 = x0.T @ dh1; gb1 = dh1.sum(0)
            grads = [gW1, gb1, gW2, gb2, gW3, gb3]
            t = ep * 10000 + s
            for i, (p, g) in enumerate(zip(params, grads)):
                ms[i] = 0.9 * ms[i] + 0.1 * g
                vs[i] = 0.999 * vs[i] + 0.001 * g * g
                p -= lr * (ms[i] / (1 - 0.9 ** (t + 1))) / (np.sqrt(vs[i] / (1 - 0.999 ** (t + 1))) + 1e-8)
        if ep % 10 == 9 or ep == 0:
            pv, _ = forward(Xva_n)
            err = np.abs(pv - Yva)
            print(f"epoch {ep+1}: val MAE per band {err.mean(0).round(2)} dB, overall {err.mean():.2f} dB")

    pv, _ = forward(Xva_n)
    err = np.abs(pv - Yva)
    # baseline: fixed gains = train-set mean per band
    base = np.abs(Ytr.mean(0)[None, :] - Yva)
    print(f"FINAL val MAE {err.mean():.2f} dB (bands {err.mean(0).round(2)}) vs fixed-gain baseline {base.mean():.2f} dB")

    # --- export header
    def carr(name, arr):
        flat = ", ".join(f"{v:.7g}f" for v in np.array(arr).flatten())
        return f"static const float {name}[{np.array(arr).size}] = {{ {flat} }};\n"
    with open("Source/dsp/BweWeights.h", "w") as fp:
        fp.write("// BweWeights.h -- generated by tools/train_bwe.py. Do not edit by hand.\n")
        fp.write("// Tiny MLP (11 -> 48 -> 48 -> 3) predicting HF band gains (dB) for BWE.\n#pragma once\n\nnamespace bwe_weights {\n")
        fp.write(carr("kMean", mu) + carr("kStd", sd))
        fp.write(carr("kW1", W1) + carr("kB1", b1) + carr("kW2", W2) + carr("kB2", b2) + carr("kW3", W3) + carr("kB3", b3))
        fp.write("} // namespace bwe_weights\n")
    print("wrote Source/dsp/BweWeights.h")

if __name__ == "__main__":
    main()
